const MERMAID_INIT = `<script src="https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"></script>
<script>mermaid.initialize({startOnLoad:false,theme:'neutral',flowchart:{useMaxWidth:true,htmlLabels:true,curve:'basis',nodeSpacing:28,rankSpacing:36,padding:10}});
window.addEventListener('load',async()=>{await mermaid.run();document.body.dataset.ready='1';});</script>`;


(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1920, height: 1080 } });
  const p = await ctx.newPage();
  for (const [name, html0] of Object.entries(slides)) {
    const html = html0.replace('__MERMAID__', MERMAID_INIT);
    await p.setContent(html, { waitUntil: 'load' });
    if (html.includes('mermaid.run')) await p.waitForSelector('body[data-ready="1"]', { timeout: 30000 });
    await p.waitForTimeout(300);
    await p.screenshot({ path: path.join(OUT, `${name}.png`) });
    console.log('slide', name);
  }
  await browser.close();
})();
